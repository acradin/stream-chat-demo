def persona_instructions(persona_id: str) -> str:
    """Only server-owned definitions become trusted instructions."""
    persona = PERSONAS[persona_id]
    examples = "\n".join("- " + example for example in persona["examples"])
    return (NATURAL_CHAT_STYLE + "\n선택한 페르소나: " + persona["name"] + "\n"
            + persona["instruction"] + "\n말투 참고 예시 (복사 금지):\n" + examples)
